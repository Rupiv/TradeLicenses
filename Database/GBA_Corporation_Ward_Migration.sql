       t.assemblyNativeName, ac.constituencyID, lw.wardID, m.mohID, t.matchMethod
FROM #gbaWard t
JOIN dbo.Master_GBAZone z ON z.corporationID = t.corporationID AND z.zoneName = t.zoneName
